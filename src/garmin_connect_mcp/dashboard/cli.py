"""``garmin-connect-mcp dashboard``: sync, build and open the dashboard."""

import argparse
import os
import shlex
import stat
import sys
import tempfile
import webbrowser
from pathlib import Path
from typing import Any

from .analytics import correlations
from .cache import ChunkCache, default_cache_dir
from .normalize import build_dataset
from .render import render_html, write_dashboard
from .sync import REQUEST_PAUSE_SECONDS, sync

APP_NAME = "Garmin Dashboard"


def build(cache: ChunkCache) -> dict[str, Any]:
    """Cache -> dataset with correlations attached."""
    dataset = build_dataset(cache)
    dataset["correlations"] = correlations(dataset)
    return dataset


def _client() -> Any:
    from ..auth import can_authenticate, load_config
    from ..client import init_garmin_client

    config = load_config()
    if not can_authenticate(config):
        raise SystemExit("Garmin is not authenticated. Run: garmin-connect-mcp auth")
    client = init_garmin_client(config)
    if client is None:
        raise SystemExit("Could not sign in to Garmin. Run: garmin-connect-mcp auth")
    return client


def _sync(cache: ChunkCache, args: argparse.Namespace) -> dict[str, Any]:
    if args.demo:
        from .demo import DemoGarmin

        client, pause = DemoGarmin(), 0.0
    else:
        client, pause = _client(), REQUEST_PAUSE_SECONDS
    report = sync(
        client,
        cache,
        since=args.since,
        full=args.full,
        pause=pause,
        progress=None if args.demo else lambda line: print(f"  ↓ {line}", file=sys.stderr),
    )
    print(
        f"Synced: {report.fetched} downloaded, {report.cached} already cached, "
        f"{len(report.errors)} errors.",
        file=sys.stderr,
    )
    for err in report.errors:
        print(f"  ! {err['source']} {err['window']}: {err['error']}", file=sys.stderr)
    return {"fetched": report.fetched, "cached": report.cached, "errors": report.errors}


def install_app(python: str = sys.executable, apps_dir: Path | None = None) -> Path:
    """Create a double-clickable macOS app that runs ``dashboard --serve``."""
    apps_dir = apps_dir or Path.home() / "Applications"
    app = apps_dir / f"{APP_NAME}.app"
    macos = app / "Contents" / "MacOS"
    macos.mkdir(parents=True, exist_ok=True)
    log = default_cache_dir() / "app.log"
    script = macos / "garmin-dashboard"
    script.write_text(
        "#!/bin/bash\n"
        "# Generated by `garmin-connect-mcp dashboard install-app`.\n"
        f"mkdir -p {shlex.quote(str(log.parent))}\n"
        f"exec {shlex.quote(python)} -m garmin_connect_mcp.cli dashboard --serve "
        f">> {shlex.quote(str(log))} 2>&1\n",
        encoding="utf-8",
    )
    script.chmod(script.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    (app / "Contents" / "Info.plist").write_text(
        f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>{APP_NAME}</string>
  <key>CFBundleDisplayName</key><string>{APP_NAME}</string>
  <key>CFBundleIdentifier</key><string>io.github.scortes5.garmin-dashboard</string>
  <key>CFBundleExecutable</key><string>garmin-dashboard</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>LSUIElement</key><true/>
</dict>
</plist>
""",
        encoding="utf-8",
    )
    return app


def _parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="garmin-connect-mcp dashboard",
        description="Download your Garmin history and open it as an interactive dashboard.",
    )
    p.add_argument("action", nargs="?", choices=["install-app"], help="install-app: macOS app")
    p.add_argument("--no-sync", action="store_true", help="use cached data only (offline)")
    p.add_argument("--full", action="store_true", help="re-download all history, not just new days")
    p.add_argument("--since", type=int, metavar="YEAR", help="first year to download")
    p.add_argument("--output", type=Path, metavar="FILE", help="where to write the HTML file")
    p.add_argument("--no-open", action="store_true", help="do not open the browser")
    p.add_argument("--serve", action="store_true", help="serve locally with an in-page sync button")
    p.add_argument("--port", type=int, default=0, help="port for --serve (default: any free port)")
    p.add_argument("--demo", action="store_true", help="synthetic data; no Garmin account needed")
    return p


def main(argv: list[str]) -> None:
    args = _parser().parse_args(argv)
    if args.demo:
        # Never mix invented numbers into the real cache.
        cache = ChunkCache(Path(tempfile.mkdtemp(prefix="garmin-dashboard-demo-")))
        args.no_sync = False
    else:
        cache = ChunkCache(default_cache_dir())

    if args.action == "install-app":
        if sys.platform != "darwin":
            raise SystemExit("install-app is only available on macOS.")
        app = install_app()
        print(f"Installed {app}\nOpen it from Finder, Launchpad or Spotlight ('{APP_NAME}').")
        return

    if not args.no_sync:
        _sync(cache, args)

    if args.serve:
        from .server import DashboardServer

        server = DashboardServer(
            args.port,
            page=lambda: render_html(build(cache), live=True),
            do_sync=lambda: _sync(
                cache, argparse.Namespace(since=None, full=False, demo=args.demo)
            ),
        )
        print(f"Dashboard running at {server.url} (Ctrl+C to stop)", file=sys.stderr)
        if not args.no_open:
            webbrowser.open(server.url)
        try:
            server.serve_until_idle()
        except KeyboardInterrupt:
            pass
        return

    output = args.output or Path(
        os.environ.get("GARMIN_DASHBOARD_HTML", cache.root / "dashboard.html")
    )
    path = write_dashboard(build(cache), output)
    print(f"Dashboard written to {path}", file=sys.stderr)
    if not args.no_open:
        webbrowser.open(path.resolve().as_uri())
